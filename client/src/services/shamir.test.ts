import { describe, expect, it } from 'vitest';
import { combine, split } from './shamir';

function hex(h: string): Uint8Array {
  return Uint8Array.from(h.match(/../g)!.map((b) => parseInt(b, 16)));
}

function toHex(b: Uint8Array): string {
  return Array.from(b, (x) => x.toString(16).padStart(2, '0')).join('');
}

/** Every size-k subset of the items, in order. */
function subsets<T>(items: T[], k: number): T[][] {
  if (k === 0) return [[]];
  if (items.length < k) return [];
  const [head, ...rest] = items;
  return [...subsets(rest, k - 1).map((s) => [head, ...s]), ...subsets(rest, k)];
}

const secret = crypto.getRandomValues(new Uint8Array(32));

describe('shamir split/combine', () => {
  for (let n = 2; n <= 7; n++) {
    for (let k = 2; k <= n; k++) {
      it(`round trips every ${k}-subset of ${n} shares`, () => {
        const shares = split(secret, n, k);
        expect(shares).toHaveLength(n);
        shares.forEach((s, i) => {
          expect(s.length).toBe(secret.length + 1);
          expect(s[s.length - 1]).toBe(i + 1);
        });
        for (const subset of subsets(shares, k)) {
          expect(toHex(combine(subset))).toBe(toHex(secret));
        }
      });
    }
  }

  it('also works with more than k shares and with other secret lengths', () => {
    const odd = crypto.getRandomValues(new Uint8Array(5));
    const shares = split(odd, 5, 3);
    expect(toHex(combine(shares))).toBe(toHex(odd));
    expect(toHex(combine(shares.slice(1, 5)))).toBe(toHex(odd));
    const one = Uint8Array.of(0);
    expect(toHex(combine(split(one, 3, 2).slice(0, 2)))).toBe('00');
  });

  it('does not recover the secret from k-1 shares', () => {
    for (const [n, k] of [[3, 2], [5, 3], [7, 7]] as const) {
      for (const subset of subsets(split(secret, n, k), k - 1)) {
        if (subset.length < 2) continue; // combine needs at least two
        expect(toHex(combine(subset))).not.toBe(toHex(secret));
      }
    }
  });

  it('produces different shares on each call', () => {
    expect(toHex(split(secret, 3, 2)[0])).not.toBe(toHex(split(secret, 3, 2)[0]));
  });

  it('combines a fixed vector made by an independent Python reference', () => {
    // Generated by the script in the task report; 5 shares, threshold 3.
    const shares = [
      '4873768984af9295e08b8ea1bc476a6d7863e6f9f4dfc205103b3e512c371a1d01',
      '61beff1d201fde914ff0d13e43b190bf6a35347b46b9f85a1fe0c16e88d7361902',
      '39dc9b87b0a55a13b7624584e3ebe4cd3277f0a196431c7827f2d51488cd022b03',
      'dbe3478b408edc5270a55a62b23e9a4f717f2c62a9d1b5394139c653d9d7c51004',
      '83812311d03458d08837ced81264ee3d293de8b8792b511b792bd229d9cdf12205',
    ].map(hex);
    const expected = '101112131415161718191a1b1c1d1e1f202122232425262728292a2b2c2d2e2f';
    for (const subset of subsets(shares, 3)) {
      expect(toHex(combine(subset))).toBe(expected);
    }
  });
});

describe('shamir split rejections', () => {
  it.each([[1, 1], [8, 2], [2, 3], [5, 1], [5, 6], [0, 0], [3, 8], [2.5, 2], [3, 2.5]])(
    'rejects n=%d k=%d',
    (n, k) => {
      expect(() => split(secret, n, k)).toThrow();
    },
  );

  it('rejects an empty secret', () => {
    expect(() => split(new Uint8Array(0), 3, 2)).toThrow();
  });
});

describe('shamir combine rejections', () => {
  const shares = split(secret, 4, 2);

  it('rejects fewer than two shares', () => {
    expect(() => combine([])).toThrow();
    expect(() => combine([shares[0]])).toThrow();
  });

  it('rejects a share with x-coordinate 0', () => {
    const bad = shares[1].slice();
    bad[bad.length - 1] = 0;
    expect(() => combine([shares[0], bad])).toThrow();
  });

  it('rejects duplicated x-coordinates', () => {
    expect(() => combine([shares[0], shares[2], shares[0].slice()])).toThrow();
  });

  it('rejects shares of unequal length', () => {
    expect(() => combine([shares[0], shares[1].slice(1)])).toThrow();
  });

  it('rejects a share too short to hold a value and an x-coordinate', () => {
    expect(() => combine([Uint8Array.of(1), Uint8Array.of(2)])).toThrow();
  });
});
